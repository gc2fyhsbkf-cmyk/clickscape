#!/usr/bin/env python3
"""Bundle every game script into app.js (one download instead of ~35) and point index.html / sw.js at it.
usage: python3 tools/build.py 9.8      (run from the repo root after editing any .js file)"""
import json, re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
ver = sys.argv[1]
files = [l.strip() for l in (root / 'tools/files.txt').read_text().splitlines() if l.strip()]
parts = [json.dumps((root / f).read_text() + f'\n//# sourceURL={f}\n') for f in files]
loader = ("/* Clickscape bundle — generated by tools/build.py; edit the source files, not this. */\n"
          "(function () { var F = [\n" + ',\n'.join(parts) + "\n];\n"
          "  for (var i = 0; i < F.length; i++) { var s = document.createElement('script'); s.textContent = F[i]; document.head.appendChild(s); }\n})();\n")
(root / 'app.js').write_text(loader)
html = (root / 'index.html').read_text()
html = re.sub(r'(\s*<script src="[a-z0-9]+\.js\?v=[0-9.]+"></script>)+', f'\n  <script src="app.js?v={ver}"></script>', html, count=1)
html = re.sub(r'\?v=[0-9.]+', f'?v={ver}', html); html = re.sub(r'>v[0-9.]+<', f'>v{ver}<', html)
(root / 'index.html').write_text(html)
sw = (root / 'sw.js').read_text()
sw = re.sub(r"const VERSION = '[^']+'", f"const VERSION = 'clickscape-v{ver}'", sw)
sw = re.sub(r"(?:'[a-z0-9]+\.js\?v=[0-9.]+',\s*)+", f"'app.js?v={ver}', ", sw)
sw = re.sub(r'\?v=[0-9.]+', f'?v={ver}', sw)
(root / 'sw.js').write_text(sw)
print(f'app.js: {len(files)} files, {len(loader)//1024} KB · index.html & sw.js → v{ver}')
